export const EMOJI_TABLE: readonly Entry[] = Object.freeze(ROWS.map((row) => Object.freeze(row)));

const FINGERPRINT_SIZE = 12;
const SHORT_SIZE = 4;

/** 12 table entries derived from the first 12 bytes of SHA-256(pub); `short` is the first four emoji. */
export function fingerprint(pub: Uint8Array): { emoji: string[]; short: string[]; zh: string[]; en: string[] } {
  const emoji: string[] = [];
  const zh: string[] = [];
  const en: string[] = [];
  for (const byte of sha256(pub).subarray(0, FINGERPRINT_SIZE)) {
    const row = EMOJI_TABLE[byte];
    if (!row) throw new Error(`emoji table index out of range: ${byte}`);
    emoji.push(row.emoji);
    zh.push(row.zh);
    en.push(row.en);
  }
  return { emoji, short: emoji.slice(0, SHORT_SIZE), zh, en };
}
